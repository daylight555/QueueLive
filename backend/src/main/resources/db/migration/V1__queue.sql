CREATE TABLE help_queue (
    id SMALLINT PRIMARY KEY CHECK (id = 1),
    is_open BOOLEAN NOT NULL DEFAULT FALSE,
    next_number BIGINT NOT NULL DEFAULT 1 CHECK (next_number > 0)
);
